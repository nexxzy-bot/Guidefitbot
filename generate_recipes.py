def pick(items, exclude=None):
    if exclude is None:
        return random.choice(items)
    filtered = [i for i in items if i not in exclude]
    return random.choice(filtered) if filtered else random.choice(items)

def calc(ingredients):
    total = {"kcal": 0, "protein": 0, "fat": 0, "carbs": 0}
    for name, amount in ingredients:
        info = DB.get(name, {"kcal": 0, "p": 0, "f": 0, "c": 0})
        factor = amount / 100.0
        total["kcal"] += info["kcal"] * factor
        total["protein"] += info["p"] * factor
        total["fat"] += info["f"] * factor
        total["carbs"] += info["c"] * factor
    return {k: round(v, 1) for k, v in total.items()}

def goals(kcal, protein, category):
    g = []
    if kcal < 500 and category in ("breakfast", "snack"):
        g.append("lose")
    elif kcal < 700 and category in ("lunch", "dinner"):
        g.append("lose")
    if kcal > 600 or protein > 35:
        g.append("gain")
    if not g or (400 <= kcal <= 800 and 15 <= protein <= 45):
        g.append("maintain")
    if not g:
        g.append("maintain")
    return g

