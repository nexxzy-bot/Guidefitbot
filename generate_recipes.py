def generate_category(templates, category, count):
    recipes = []
    for i in range(count):
        tmpl = random.choice(templates)
        name, ingredients, steps = tmpl()
        nutrition = calc(ingredients)
        g = goals(nutrition["kcal"], nutrition["protein"], category)
        recipes.append({
            "id": i + 1,
            "name": name,
            "ingredients": [{"name": n, "amount": a, "unit": "г" if n not in ("молоко 3.2%", "молоко 1.5%", "сливки 20%", "сливки 10%", "кефир 2.5%", "ряженка", "сметана 15%", "оливковое масло", "кокосовое масло", "сливочное масло", "масло кунжутное", "льняное масло", "авокадо-масло", "масло гhee", "соевый соус", "бальзамический уксус", "яблочный уксус", "кокосовое молоко", "куриный бульон", "овощной бульон", "вино белое сухое", " miso-паста", "сок лимона", "сок лайма", "вода", "кофе эспрессо", "чай зелёный", "кокосовая вода", "миндальное молоко", "овсяное молоко", "рисовое молоко", "соевое молоко", "кокосовые сливки", "йогурт питьевой", "кефир питьевой", "трюфельное масло") else "г"} for n, a in ingredients],
            "calories": nutrition["kcal"],
            "protein": nutrition["protein"],
            "fat": nutrition["fat"],
            "carbs": nutrition["carbs"],
            "steps": steps,
            "category": category,
            "goals": g
        })
    return recipes

def main():
    all_recipes = []
    all_recipes.extend(generate_category(BREAKFAST_TEMPLATES, "breakfast", 100))
    all_recipes.extend(generate_category(LUNCH_TEMPLATES, "lunch", 100))
