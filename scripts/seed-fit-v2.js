(async () => {
  // db.js сеет каталоги асинхронно (seedIfChanged -> stmt.finalize) — на чистой БД сидер
  // мог прочитать exercises раньше сида. Ждём появления упражнений до 15 секунд.
  const sleep = (ms) => new Promise(r => setTimeout(r, ms));
  let exs = [];
  for (let i = 0; i < 30; i++) {
    exs = await all('SELECT id FROM exercises');
    if (exs.length > 0) break;
    await sleep(500);
  }
  // упражнения, на которые ссылаются программы, должны существовать
  const exIds = new Set(exs.map(x => x.id));
  const missing = [...new Set(PROGRAMS.flatMap(p => p.week.flatMap(d => d[1].map(e => e[0]))))].filter(id => !exIds.has(id));
  if (missing.length) { console.error('Нет упражнений в БД:', missing); process.exit(1); }

  await q('BEGIN');
  try {
    for (const p of PROGRAMS) {
      await q(`DELETE FROM fit_exercises WHERE program_day_id IN (SELECT id FROM fit_days WHERE program_id = ?)`, [p.id]);
      await q('DELETE FROM fit_days WHERE program_id = ?', [p.id]);
      await q(`INSERT OR REPLACE INTO fit_programs (id, name, category, level, weeks, days_per_week, minutes, description, location)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'home')`,
        [p.id, p.name, p.cat, p.lvl, p.weeks, p.dpw, p.min, p.desc]);
      // расписание: недели повторяют шаблонную неделю
      let dayNo = 0;
      for (let w = 1; w <= p.weeks; w++) {
        for (let d = 1; d <= p.week.length; d++) {
          const t = p.week[d - 1];
          dayNo++;
          const r = await q(`INSERT INTO fit_days (id, program_id, week, day, title, description)
                             VALUES (?, ?, ?, ?, ?, ?)`,
            [p.id * 100 + w * 10 + d, p.id, w, d, t[0], 'Неделя ' + w + ' из ' + p.weeks]);
          const dayId = r.lastID;
          for (const [exId, sets, reps, rest] of t[1]) {
            await q(`INSERT INTO fit_exercises (program_day_id, exercise_id, sets, reps, rest_seconds, notes)
                     VALUES (?, ?, ?, ?, ?, '')`, [dayId, exId, sets, reps, rest]);
          }
        }
      }
    }
    for (const y of YOGA) {
      await q(`INSERT OR REPLACE INTO yoga_programs (id, title, focus, level, minutes, description, poses)
               VALUES (?, ?, ?, ?, ?, ?, ?)`,
        [y.id, y.title, y.focus, y.lvl, y.min, y.desc, JSON.stringify(y.poses)]);
    }
    await q("INSERT OR REPLACE INTO meta (key, value) VALUES ('fit:v2:seeded', ?)",
      [JSON.stringify({ programs: PROGRAMS.length, yoga: YOGA.length, at: new Date().toISOString() })]);
    await q('COMMIT');
    console.log(`Готово: ${PROGRAMS.length} программ (fat=${PROGRAMS.filter(p=>p.cat==='fat').length}, muscle=${PROGRAMS.filter(p=>p.cat==='muscle').length}, cardio=${PROGRAMS.filter(p=>p.cat==='cardio').length}), ${YOGA.length} практик йоги`);
    process.exit(0);
  } catch (e) {
    await q('ROLLBACK');
    throw e;
  }
})().catch(e => { console.error('Ошибка сидера:', e.message); process.exit(1); });
